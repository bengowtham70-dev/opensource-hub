export const useI18n = create((set, get) => ({
  locale: typeof window !== "undefined" ? localStorage.getItem("osh:locale") || "en" : "en",
  setLocale: (code) => {
    if (typeof window !== "undefined") {
      localStorage.setItem("osh:locale", code);
    }
    set({ locale: code });
  },
  t: (key) => {
    const { locale } = get();
    return TRANSLATIONS[locale]?.[key] || TRANSLATIONS.en[key] || key;
  },
}));
