// plans/PLAN_PHASE2.md Phase 9 — payload generator for Bun-compiled single-file
// binaries (PRD section 30). Walks every runtime-read file and emits
// src/server/payload.generated.js (gitignored; only exists inside release CI
// builds). Run AFTER `npm run build` so dist/client assets are included.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");
const OUT = path.join(root, "src", "server", "payload.generated.js");

const EXACT_FILES = [
  "package.json",
  "src/data/alternatives.json",
  "src/data/snapshots-seed.json",
  "src/data/lists.json",
  "src/data/health-diff.json",
];

function walk(dir, base = "") {
  const out = [];
  let entries;
  try {
    entries = fs.readdirSync(path.join(dir, base), { withFileTypes: true });
  } catch {
    return out; // optional dir (e.g. dist/client not built yet)
  }
  for (const e of entries) {
    const rel = base ? `${base}/${e.name}` : e.name;
    if (e.isDirectory()) out.push(...walk(dir, rel));
    else out.push(rel);
  }
  return out;
}

const files = new Set();
for (const f of EXACT_FILES) {
  if (fs.existsSync(path.join(root, f))) files.add(f);
}
for (const f of walk(path.join(root, "content", "learn"))) files.add(`content/learn/${f}`);
for (const f of walk(path.join(root, "dist", "client"))) files.add(`dist/client/${f}`);

const entries = [...files].sort().map((rel) => {
  const content = fs.readFileSync(path.join(root, rel), "utf8");
  return `  ${JSON.stringify(rel)}: ${JSON.stringify(content)}`;
});

fs.writeFileSync(
  OUT,
  `// AUTO-GENERATED by scripts/make-bun-payload.mjs — do not edit.\n` +
    `// Embedded into Bun-compiled binaries; gitignored for npm installs.\n` +
    `import { registerPayload } from "./repo-files.js";\n` +
    `registerPayload({\n${entries.join(",\n")}\n});\n`
);
console.log(`payload written: ${files.size} files (${entries.length} entries)`);
